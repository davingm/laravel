#!/usr/bin/env node
/**
 * AutoLaravel CLI setup script
 * Installs the `artisan` command so it works without typing `php artisan`.
 *
 * Called automatically after Composer generates the project autoloader.
 * Can also be run manually: node .auto/setup.js
 *
 * - Unix / Git Bash / WSL: installs a POSIX `artisan` shell script
 * - Windows: also installs `artisan.cmd` for PowerShell and cmd.exe
 */

import { writeFileSync, readFileSync, chmodSync, mkdirSync, existsSync, accessSync, constants } from 'node:fs';
import { resolve, dirname, delimiter, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const __dir = dirname(fileURLToPath(import.meta.url));
const cliPath = resolve(__dir, 'cli.js');
const isWindows = process.platform === 'win32';

const MANAGED_MARKERS = [
    'AutoLaravel CLI',
    'davingm Laravel CLI',
    'Auto-generated by .auto/setup.js',
    'Auto-generated by .davingm/setup.js',
];

function isManagedLauncher(contents) {
    return MANAGED_MARKERS.some((marker) => contents.includes(marker));
}

// POSIX launcher for Git Bash, WSL, Linux, and macOS
const shellScriptContent = `#!/usr/bin/env sh
# artisan – AutoLaravel CLI
# Auto-generated by .auto/setup.js
project_dir="$PWD"

while :; do
    if [ -f "$project_dir/.auto/cli.js" ]; then
        exec node "$project_dir/.auto/cli.js" "$@"
    fi

    parent_dir=$(dirname "$project_dir")
    if [ "$parent_dir" = "$project_dir" ]; then
        break
    fi
    project_dir="$parent_dir"
done

printf '%s\\n' 'artisan: no AutoLaravel project found in this directory or its parents.' >&2
exit 1
`;

// Windows cmd launcher for PowerShell and Command Prompt
const cmdScriptContent = `@ECHO OFF
SETLOCAL EnableExtensions
REM artisan – AutoLaravel CLI
REM Auto-generated by .auto/setup.js

SET "project_dir=%CD%"

:find_project
IF EXIST "%project_dir%\\.auto\\cli.js" (
    node "%project_dir%\\.auto\\cli.js" %*
    EXIT /B %ERRORLEVEL%
)

FOR %%I IN ("%project_dir%\\..") DO SET "parent_dir=%%~fI"
IF /I "%parent_dir%"=="%project_dir%" GOTO not_found
SET "project_dir=%parent_dir%"
GOTO find_project

:not_found
ECHO artisan: no AutoLaravel project found in this directory or its parents. 1>&2
EXIT /B 1
`;

function installFile(target, contents, { chmod = false } = {}) {
    if (existsSync(target)) {
        const existing = readFileSync(target, 'utf8');
        if (!isManagedLauncher(existing)) {
            console.warn(`[auto] Skipping existing command: ${target}`);

            return false;
        }
    }

    writeFileSync(target, contents, { encoding: 'utf8' });
    if (chmod) {
        try {
            chmodSync(target, 0o755);
        } catch {
            // chmod is best-effort on Windows filesystems
        }
    }

    console.log(`[auto] artisan installed → ${target}`);

    return true;
}

// ── Determine install targets ─────────────────────────────────────────────────
const home = homedir();
const pathEntries = (process.env.PATH ?? '')
    .split(delimiter)
    .filter(Boolean)
    .map((entry) => resolve(entry));
const pathKeys = new Set(pathEntries.map((entry) => (isWindows ? entry.toLowerCase() : entry)));

// Prefer the real user Composer home on Windows even if COMPOSER_HOME is
// temporarily overridden (e.g. sandboxed installs).
const composerHome = isWindows
    ? resolve(process.env.APPDATA ?? resolve(home, 'AppData', 'Roaming'), 'Composer')
    : (process.env.COMPOSER_HOME
        ?? resolve(process.env.XDG_CONFIG_HOME ?? resolve(home, '.config'), 'composer'));
const composerBin = resolve(process.env.COMPOSER_BIN_DIR ?? resolve(composerHome, 'vendor', 'bin'));
const npmBin = isWindows
    ? resolve(process.env.APPDATA ?? resolve(home, 'AppData', 'Roaming'), 'npm')
    : null;

// Bare `artisan` only works when its directory is already on PATH. Prefer the
// Composer global bin, then npm's global bin and conventional user bins.
const candidates = [composerBin, npmBin, resolve(home, 'bin'), resolve(home, '.local', 'bin')]
    .filter(Boolean)
    .map((directory) => resolve(directory))
    .filter((directory, index, all) => all.indexOf(directory) === index)
    .filter((directory) => pathKeys.has(isWindows ? directory.toLowerCase() : directory));

const targetDirectories = [];
for (const directory of candidates) {
    try {
        if (!existsSync(directory)) {
            mkdirSync(directory, { recursive: true });
        }
        accessSync(directory, constants.W_OK);
        targetDirectories.push(directory);
    } catch {
        // Continue to another already-PATH'd, user-writable bin directory.
    }
}

let installed = false;

for (const directory of targetDirectories) {
    // Always install the POSIX launcher (used by Git Bash on Windows too).
    if (installFile(join(directory, 'artisan'), shellScriptContent, { chmod: true })) {
        installed = true;
    }

    // On Windows, also install artisan.cmd so PowerShell/cmd can run `artisan`.
    if (isWindows && installFile(join(directory, 'artisan.cmd'), cmdScriptContent)) {
        installed = true;
    }
}

if (!installed) {
    console.warn('[auto] Could not install artisan in a writable directory already on PATH.');
    console.warn('[auto] Ensure Composer global bin is on PATH, then run: node .auto/setup.js');
    console.warn('[auto] Or from the project directory use the local artisan.cmd / run:');
    console.warn(`[auto]   node "${cliPath.replace(/\\/g, '/')}" <command>`);
} else {
    console.log('[auto] Setup complete. Run: artisan make:dashboard');
}
